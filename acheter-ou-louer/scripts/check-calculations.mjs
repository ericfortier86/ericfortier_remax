import assert from 'node:assert/strict';
import { minimumDown, premiumRate, payment, compare, capacity, defaultInputs } from '../lib/calculations.ts';
assert.equal(minimumDown(500000),25000);
assert.equal(minimumDown(600000),35000);
assert.equal(minimumDown(1500000),300000);
assert.equal(premiumRate(400000,80000),0);
assert.equal(premiumRate(400000,20000),.04);
assert.ok(Math.abs(payment(320000,4)-1683.27)<.02,'Canadian semiannual mortgage payment');
assert.equal(payment(300000,0),1000);
const flat={...defaultInputs,price:300000,down:300000,rate:0,rent:1000,years:1,appreciation:0,returnRate:0,rentGrowth:0,taxes:0,maintenance:0,insurance:0,renterInsurance:0,condo:0,closing:0,selling:0};
assert.equal(compare(flat).selected.difference,12000,'Owner invests monthly savings, renter invests cash upfront');
assert.equal(compare({...defaultInputs,down:1000}).valid,false);
assert.equal(compare({...defaultInputs,down:500000}).valid,false);
assert.ok(compare({...defaultInputs,rent:4000}).selected.difference>compare(defaultInputs).selected.difference);
assert.ok(compare({...defaultInputs,appreciation:-5}).selected.difference<compare(defaultInputs).selected.difference);
assert.equal(capacity({...defaultInputs,savings:0}).price,0);
assert.equal(capacity({...defaultInputs,income:0}).price,0);
assert.ok(capacity({...defaultInputs,income:50000}).price<capacity(defaultInputs).price);
assert.ok(capacity({...defaultInputs,debts:3000}).price<capacity(defaultInputs).price);
assert.ok(capacity(defaultInputs).needed<=defaultInputs.savings);
const fullTerm = compare({...flat,down:60000,rent:0,years:25});
assert.equal(fullTerm.points.length,25,'Projection includes every year through year 25');
assert.equal(fullTerm.selected.year,25,'The final slider value selects year 25');
assert.ok(Math.abs(fullTerm.selected.owner-300000)<.01,'The loan is fully paid at the end of the 25-year amortization');
assert.ok(Math.abs(fullTerm.selected.difference)<.01,'Equal cash flows and zero investment return yield equal wealth at 25 years');
assert.equal(compare({...flat,closing:1}).closing,3000,'One percent purchase costs are charged upfront');
assert.equal(compare({...flat,rent:0,selling:4}).selected.owner,288000,'Four percent selling costs reduce resale proceeds');
assert.ok(compare({...flat,rentGrowth:3.1}).selected.difference>compare(flat).selected.difference,'Rent growth changes invested savings');
assert.ok(compare({...defaultInputs,years:25}).points.every(p=>Number.isFinite(p.owner)&&Number.isFinite(p.renter)),'All 25-year points remain finite');
console.log('Financial checks passed, including the complete 25-year projection.');
